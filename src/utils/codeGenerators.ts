import { AIButtonStudioComponent, DesignTokens } from '../types';

/**
 * Generates automated header attribution watermark per Section 1.5
 */
function getAttributionHeader(attribution: AIButtonStudioComponent['attribution']): string {
  return `/**
 * ============================================================================
 * AI Button Studio - Auto-Credit & Ethical Attribution Registry
 * Author / Credit: ${attribution.credit_owner}
 * License: ${attribution.license_type}
 * Source Repository: ${attribution.source_repository || 'https://github.com/mutiagent-base/ai-button-studio-app-design'}
 * Generated by AI Button Studio Compiler
 * ============================================================================
 */\n\n`;
}

export function generateReactCode(component: AIButtonStudioComponent, tokens: DesignTokens): string {
  const isRGB = component.effects.special_features.includes('rgb_running_border');
  const isDynamicShadow = component.effects.special_features.includes('dynamic_shadow_cursor_tracking');

  return `${getAttributionHeader(component.attribution)}import React, { useState, useRef, useEffect } from 'react';
import { Sparkles, Rocket, Search, Plus, ArrowRight, Check, Loader2 } from 'lucide-react';

export interface LivingButtonProps {
  onClick?: () => void;
  disabled?: boolean;
  className?: string;
}

export const ${toPascalCase(component.content.label || 'LivingButton')}: React.FC<LivingButtonProps> = ({
  onClick,
  disabled = false,
  className = '',
}) => {
  const [state, setState] = useState<'idle' | 'hover' | 'loading' | 'success' | 'error'>('idle');
  const buttonRef = useRef<HTMLButtonElement>(null);

  ${isDynamicShadow ? `// 1. Dynamic Cursor Proximity Shadow Tracking (Section 3.3.A)
  useEffect(() => {
    const btn = buttonRef.current;
    if (!btn || disabled || state === 'loading') return;

    const handleMouseMove = (event: MouseEvent) => {
      const bounds = btn.getBoundingClientRect();
      const centerX = bounds.left + bounds.width / 2;
      const centerY = bounds.top + bounds.height / 2;

      const diffX = event.clientX - centerX;
      const diffY = event.clientY - centerY;

      // Dampen projection factor
      const shadowOffsetX = -(diffX / 16);
      const shadowOffsetY = -(diffY / 16);

      const distance = Math.sqrt(diffX * diffX + diffY * diffY);
      const blurRadius = Math.min(28, Math.max(8, 3500 / (distance + 1)));

      btn.style.boxShadow = \`\${shadowOffsetX.toFixed(1)}px \${shadowOffsetY.toFixed(1)}px \${blurRadius.toFixed(1)}px rgba(0, 0, 0, ${tokens.shadowIntensity})\`;
    };

    const handleMouseLeave = () => {
      btn.style.boxShadow = '';
    };

    window.addEventListener('mousemove', handleMouseMove);
    btn.addEventListener('mouseleave', handleMouseLeave);
    return () => {
      window.removeEventListener('mousemove', handleMouseMove);
      btn.removeEventListener('mouseleave', handleMouseLeave);
    };
  }, [disabled, state]);` : ''}

  const handleClick = async (e: React.MouseEvent<HTMLButtonElement>) => {
    if (disabled || state === 'loading') return;
    setState('loading');

    try {
      if (onClick) await onClick();
      setState('success');
      setTimeout(() => setState('idle'), 1500);
    } catch {
      setState('error');
      setTimeout(() => setState('idle'), 1200);
    }
  };

  return (
    <button
      ref={buttonRef}
      id="${component.id}"
      type="button"
      tabIndex={${component.accessibility.tab_index}}
      aria-label="${component.accessibility.aria_label}"
      disabled={disabled || state === 'loading'}
      onClick={handleClick}
      onMouseEnter={() => setState('hover')}
      onMouseLeave={() => state !== 'loading' && state !== 'success' && setState('idle')}
      className={\`group relative inline-flex items-center justify-center gap-2.5 px-6 py-3 text-sm font-semibold tracking-wide transition-all duration-200 outline-none
        ${isRGB ? 'living-btn-rgb' : getBaseStyleClasses(component.effects.base_style)}
        \${state === 'loading' ? 'cursor-wait opacity-85' : 'cursor-pointer'}
        \${state === 'error' ? 'animate-shake !bg-rose-600 !text-white' : ''}
        \${state === 'success' ? 'animate-success-pop !bg-emerald-600 !text-white' : ''}
        \${disabled ? 'opacity-40 cursor-not-allowed filter grayscale' : 'hover:scale-[1.02] active:scale-[0.98]'}
        \${className}\`}
      style={{
        borderRadius: '${tokens.borderRadius === 9999 ? '9999px' : `${tokens.borderRadius}px`}',
        ['--btn-transition-timing' as any]: '${tokens.transitionTiming}',
        transitionTimingFunction: '${tokens.transitionTiming}',
      }}
    >
      {state === 'loading' ? (
        <>
          <Loader2 className="w-4 h-4 animate-spin text-cyan-300" />
          <span>Processing...</span>
        </>
      ) : state === 'success' ? (
        <>
          <Check className="w-4 h-4 text-white" />
          <span>Completed</span>
        </>
      ) : (
        <>
          ${renderIconJSX(component.content.icon_name)}
          <span>${component.content.label}</span>
        </>
      )}
    </button>
  );
};
`;
}

