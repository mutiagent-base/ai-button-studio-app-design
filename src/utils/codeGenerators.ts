export function generateVueCode(component: AIButtonStudioComponent, tokens: DesignTokens): string {
  return `${getAttributionHeader(component.attribution)}<template>
  <button
    id="${component.id}"
    :class="[
      'living-btn',
      '${component.effects.special_features.includes('rgb_running_border') ? 'living-btn-rgb' : ''}',
      { 'is-loading': loading }
    ]"
    :aria-label="'${component.accessibility.aria_label}'"
    :tabindex="${component.accessibility.tab_index}"
    @click="handleClick"
  >
    <span v-if="loading">Processing...</span>
    <span v-else>${component.content.label}</span>
  </button>
</template>

<script setup lang="ts">
import { ref } from 'vue';

const loading = ref(false);

const emit = defineEmits(['click']);

const handleClick = async () => {
  if (loading.value) return;
  loading.value = true;
  emit('click');
  setTimeout(() => { loading.value = false; }, 1200);
};
</script>

<style scoped>
.living-btn {
  padding: 12px 24px;
  border-radius: ${tokens.borderRadius === 9999 ? '9999px' : `${tokens.borderRadius}px`};
  background: #0f172a;
  color: #ffffff;
  font-weight: 600;
  cursor: pointer;
  transition: all 0.25s ${tokens.transitionTiming};
}
</style>
`;
}

function toPascalCase(str: string): string {
  return str
    .replace(/[^a-zA-Z0-9]/g, ' ')
    .split(' ')
    .filter(Boolean)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join('') || 'LivingButton';
}

function getBaseStyleClasses(style: string): string {
  switch (style) {
    case 'neon_blue_glow':
      return 'bg-cyan-950/80 text-cyan-200 border border-cyan-500/50 shadow-[0_0_20px_rgba(6,182,212,0.3)] hover:shadow-[0_0_30px_rgba(6,182,212,0.55)] hover:border-cyan-400';
    case 'gradient_fill':
      return 'bg-gradient-to-r from-sky-500 via-indigo-500 to-purple-600 text-white shadow-lg shadow-indigo-500/25 hover:shadow-indigo-500/45';
    case 'outline_rgb':
      return 'bg-neutral-900/90 text-white border border-neutral-700';
    case 'soft_shadow':
      return 'bg-neutral-800 text-neutral-100 border border-neutral-700/60 shadow-md shadow-black/40 hover:bg-neutral-750';
    default:
      return 'bg-sky-600 text-white shadow-md hover:bg-sky-500';
  }
}

function renderIconJSX(iconName?: string): string {
  switch (iconName) {
    case 'rocket': return '<Rocket className="w-4 h-4 text-cyan-300 group-hover:translate-x-0.5 transition-transform" />';
    case 'sparkles': return '<Sparkles className="w-4 h-4 text-amber-300 group-hover:rotate-12 transition-transform" />';
    case 'search': return '<Search className="w-4 h-4 text-neutral-300" />';
    case 'plus': return '<Plus className="w-4 h-4 text-white group-hover:rotate-90 transition-transform" />';
    case 'arrow-right': return '<ArrowRight className="w-4 h-4 text-cyan-400 group-hover:translate-x-1 transition-transform" />';
    case 'check': return '<Check className="w-4 h-4 text-emerald-400" />';
    default: return '<Sparkles className="w-4 h-4 text-cyan-300" />';
  }
}
